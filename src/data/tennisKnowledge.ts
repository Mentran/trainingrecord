function levelDistance(a: TennisLevel, b: TennisLevel): number {
  return Math.abs(LEVEL_RANK[a] - LEVEL_RANK[b])
}

function dateSeed(date = new Date()): number {
  return Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000)
}

function recordText(records: TrainingRecord[]): string {
  return records.slice(0, 5).map(r => `${r.content} ${r.reflection} ${(r.tags ?? []).join(' ')}`).join(' ')
}

export function isTennisSport(sport: Sport): boolean {
  return sport.id === 'tennis'
    || sport.name.includes('网球')
    || sport.icon.includes('🎾')
    || (sport.categories.includes('正手') && sport.categories.includes('反手'))
}

export function getTennisKnowledgeCard(id?: string): TennisKnowledgeCard | undefined {
  return id ? TENNIS_KNOWLEDGE_CARDS.find(card => card.id === id) : undefined
}

export function getRecommendedTrainingPrompt(
  level: TennisLevel,
  records: TrainingRecord[],
  offset = 0,
  date = new Date(),
): TennisKnowledgeCard {
  const recentText = recordText(records)
  const scored = TENNIS_KNOWLEDGE_CARDS
    .map(card => {
      const distance = levelDistance(card.level, level)
      const categoryHit = recentText.includes(card.category) ? 3 : 0
      const titleHit = recentText.includes(card.title.slice(0, 2)) ? 1 : 0
      return { card, score: categoryHit + titleHit - distance * 2 }
    })
    .sort((a, b) => b.score - a.score || a.card.id.localeCompare(b.card.id))

  const categories = Array.from(new Set(TENNIS_KNOWLEDGE_CARDS.map(card => card.category)))
  const recentCategories = new Set(categories.filter(category => recentText.includes(category)))
  const sameLevel = scored.filter(item => item.card.level === level)
  const related = recentCategories.size > 0
    ? sameLevel.filter(item => recentCategories.has(item.card.category))
    : sameLevel
  const pool = (related.length > 0 ? related : sameLevel).map(item => item.card)

  return pool[(dateSeed(date) + offset) % pool.length] ?? TENNIS_KNOWLEDGE_CARDS[0]
}
